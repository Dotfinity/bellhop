def make_cfg(name, base, kind, prop):
    text = (HERE / base).read_text(encoding="utf-8")
    head = text[:text.index("INVARIANT")] if "INVARIANT" in text else text
    body = "INVARIANTS\n  TypeInv\n"
    if kind in ("inv", "trap"):
        body += f"  {prop}\n"
    elif kind == "prop":
        body += f"PROPERTIES\n  {prop}\n"
    path = HERE / "checks" / f"{name}.cfg"
    path.parent.mkdir(exist_ok=True)
    path.write_text(f"\\* generated by run_checks.py from {base}\n" + head + body, encoding="utf-8")
    return path


def run(name, base, kind, prop, expect):
    cfg = make_cfg(name, base, kind, prop)
    out = HERE / "checks" / f"{name}.json"
    cmd = [sys.executable, str(RUN_TLC), "Hosting.tla", "--config", f"checks/{name}.cfg", "--stop-at-first",
           "--workers", "4", "--timeout", str(HARD_TIMEOUT - 10), "--out", str(out), "--md", str(out.with_suffix(".md"))]
    if kind in ("inv", "prop", "trap"):
        cmd.append("--no-deadlock")
    p = subprocess.Popen(cmd, cwd=HERE, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
    try:
        p.wait(timeout=HARD_TIMEOUT)
    except subprocess.TimeoutExpired:
        subprocess.run(["taskkill", "/F", "/T", "/PID", str(p.pid)], capture_output=True)
        return name, "timeout", None, False, expect
    r = json.loads(out.read_text(encoding="utf-8")) if out.exists() else {"status": "error", "stats": {}}
    exc = "unexpected exception" in json.dumps(r).lower()
    return name, r["status"], r["stats"].get("distinctStates"), exc, expect


if __name__ == "__main__":
    pick = sys.argv[1:]
    names = {c[0] for c in CHECKS}
    exact = [s for s in pick if s in names]
    for c in CHECKS:
        if exact and c[0] not in exact:
            continue
        if pick and not exact and not any(s in c[0] for s in pick):
            continue
        name, status, states, exc, expect = run(*c)
        ok = (status == "passed") if expect == "holds" else (status in ("safety", "liveness"))
        print(f"{name:45s} {status:10s} {str(states):>10s} exc={exc} {'as-expected' if ok and not exc else 'CHECK'}", flush=True)
